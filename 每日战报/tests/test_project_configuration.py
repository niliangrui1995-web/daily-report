from __future__ import annotations

import re
import tomllib
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]


def test_project_has_reproducible_uv_environment() -> None:
    pyproject = REPO_ROOT / "pyproject.toml"
    lockfile = REPO_ROOT / "uv.lock"

    assert pyproject.is_file()
    assert lockfile.is_file()
    assert (REPO_ROOT / ".python-version").read_text(encoding="utf-8").strip() == "3.14"

    config = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    assert config["project"]["requires-python"] == ">=3.14,<3.15"
    assert config["tool"]["uv"]["package"] is False

    dev_dependencies = "\n".join(config["dependency-groups"]["dev"])
    for dependency in ("pytest", "ruff", "pip-audit", "detect-secrets"):
        assert dependency in dev_dependencies


